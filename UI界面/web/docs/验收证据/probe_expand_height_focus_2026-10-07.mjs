const PW = '/Users/boos/.workbuddy-ai/binaries/node/workspace/node_modules/playwright-core/index.js';
const pw = await import(PW);
const chromium = pw.chromium ?? pw.default?.chromium;
const browser = await chromium.connectOverCDP(process.env.CDP_URL);
const ctx = browser.contexts()[0];
const page = ctx.pages().find((p) => p.url().includes('127.0.0.1:3000'));
await page.bringToFront();
const cdp = await page.context().newCDPSession(page);
await cdp.send('Emulation.setDeviceMetricsOverride', { width: 1800, height: 1180, deviceScaleFactor: 1, mobile: false });
const S = 'div.overflow-auto, div[class*="overflow-y"]';
const sc = () => page.evaluate((sel) => { const a = [...document.querySelectorAll(sel)]; const e = a.find((x) => x.scrollHeight > x.clientHeight + 50) || a[0]; return e ? { scrollH: e.scrollHeight, clientH: e.clientHeight, scrollTop: Math.round(e.scrollTop), clientW: e.clientWidth } : null; }, S);
const rowH = () => page.evaluate(() => { const r = document.querySelector('tbody tr[data-token-id]'); return r ? Math.round(r.getBoundingClientRect().height * 100) / 100 : null; });
const rows = () => page.evaluate(() => document.querySelectorAll('tbody tr[data-token-id]').length);
const last = () => page.evaluate(() => { const r = document.querySelectorAll('tbody tr[data-token-id]'); return r.length ? r[r.length - 1].getAttribute('data-token-id') : null; });
const first = () => page.evaluate(() => document.querySelector('tbody tr[data-token-id]')?.getAttribute('data-token-id') ?? null);
const setTop = (t) => page.evaluate(({ sel, t }) => { const a = [...document.querySelectorAll(sel)]; const e = a.find((x) => x.scrollHeight > x.clientHeight + 50) || a[0]; e.scrollTop = t; return Math.round(e.scrollTop); }, { sel: S, t });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const clickExpand = (id) => page.evaluate((i) => { const tr = document.querySelector(`tbody tr[data-token-id="${i}"]`); tr?.querySelector('button')?.click(); }, id);
const out = {};
await page.reload({ waitUntil: 'domcontentloaded' });
await page.waitForSelector('tbody tr[data-token-id]', { timeout: 60000 });
await sleep(2000);
out.A_初始 = { sc: await sc(), rowH: await rowH(), rows: await rows() };
const id = await first();
await clickExpand(id);
await sleep(2500);
out.B_展开后 = { sc: await sc(), rowH: await rowH(), rows: await rows(), id };
await clickExpand(id);
await sleep(2500);
out.C_收起后 = { sc: await sc(), rowH: await rowH(), rows: await rows() };
await setTop(1e9);
await sleep(700);
out.D_收起后滚到底 = { sc: await sc(), last: await last(), rows: await rows() };
await setTop(0);
await sleep(500);
out.E_回顶 = { sc: await sc(), first: await first() };
await cdp.send('Emulation.clearDeviceMetricsOverride').catch(() => {});
console.log(JSON.stringify(out, null, 1));
process.exit(0);
